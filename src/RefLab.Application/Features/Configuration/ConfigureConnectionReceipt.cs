using MediatR;
using RefLab.Application.Abstractions;
using RefLab.Application.Common;
using RefLab.Application.Behaviors;
using RefLab.Domain.Identity;
using RefLab.Application.Features.Configuration;
using RefLab.Domain.Configuration;

namespace RefLab.Application.Features.Configuration;

/// <summary>
/// Sets the header and the footer of the connection receipt.
/// </summary>
/// <remarks>
/// Legacy evidence: the connection receipt layout is configured in its own configuration file, separately from the report layout.
/// </remarks>
public sealed record ConfigureConnectionReceiptCommand(string? Header = null, string? Footer = null) : IRequest<LaboratorySettingsDto>, IRequirePermission

{
    /// <inheritdoc />
    public Permission Permission => Permission.ManageSettings;
}

/// <summary>
/// Handles the ConfigureConnectionReceipt use case.
/// </summary>
public sealed class ConfigureConnectionReceiptHandler : IRequestHandler<ConfigureConnectionReceiptCommand, LaboratorySettingsDto>
{
    private readonly IAppDbContext _db;
    private readonly IUnitOfWork _unitOfWork;

    /// <summary>Initialises a new handler.</summary>
    public ConfigureConnectionReceiptHandler(
        IAppDbContext db,
        IUnitOfWork unitOfWork)
    {
        _db = db;
        _unitOfWork = unitOfWork;
    }
    /// <inheritdoc />
    public async Task<LaboratorySettingsDto> Handle(ConfigureConnectionReceiptCommand request, CancellationToken cancellationToken)
    {
        var settings = _db.Set<LaboratorySettings>().FirstOrDefault();

        if (settings is null)
        {
            settings = LaboratorySettings.Create();
            _unitOfWork.Add(settings);
        }

        settings.SetConnectionReceipt(
            request.Header ?? settings.ConnectionReceiptHeader,
            request.Footer ?? settings.ConnectionReceiptFooter);

        _unitOfWork.Update(settings);

        await _unitOfWork.SaveChangesAsync(cancellationToken);
        return LaboratorySettingsDto.FromDomain(settings);
    }
}
